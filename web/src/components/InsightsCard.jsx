import '../Styles/InsightsCard.css'

export default function InsightsCard({ data }) {
  const commits = data.kpis[0]
  const total = data.categories.reduce((sum, c) => sum + c.value, 0)
  const top = data.categories.reduce((a, b) => (b.value > a.value ? b : a))
  const share = ((top.value / total) * 100).toFixed(0)

  const items = [
    {
      title: 'Commit activity',
      icon: 'fa-solid fa-chart-line',
      text:
        'Commit activity is ' +
        (commits.change >= 0 ? 'up ' : 'down ') +
        Math.abs(commits.change) +
        '% compared to the previous period.',
    },
    {
      title: 'Top category',
      icon: 'fa-solid fa-layer-group',
      text: top.name + ' remains top activity category at ' + share + '% of total commits.',
    },
    {
      title: 'Pull requests',
      icon: 'fa-solid fa-code-pull-request',
      text: 'PRs are merged in a median of ' + data.mergeTime.median + ' which is faster than before.',
    },
  ]

  const handleDownload = () => {
    const reportText = `=========================================
    TRACEGIT - DETAILED REPORT
    =========================================
    Date: ${new Date().toLocaleString()}
    --- INSIGHTS & KEY TAKEAWAYS ---
1. Commit Activity: 
   Your commit activity is ${commits.change >= 0 ? 'up' : 'down'} by ${Math.abs(commits.change)}% compared to the previous period.

2. Top Category: 
   ${top.name} remains your top activity category at ${share}% of total commits.

3. Pull Requests: 
   Your PRs are merged in a median of ${data.mergeTime.median}, which is faster than before.

--- DATA SUMMARY ---
Total Commits: ${commits.value.toLocaleString()}
Top Contributor: ${data.contributors[0]?.login || 'N/A'}

Report generated by TraceGit.
=========================================`;

    const blob = new Blob([reportText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = 'TraceGit_Detailed_Report.txt';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };


  return (
    <div className="card insights">
      <div className="insights-header">

        <h3 className="chart-title insight-title">
          <i className="fa-solid fa-lightbulb text-amber-500 text-lg"></i>
          Insights &amp; Key Takeaways</h3>
        <button className="insights-btn" onClick={handleDownload}>
          <i className="fa-solid fa-file-arrow-down"></i> View Detailed Report
        </button>
      </div>
      <div className="insights-grid">
        {items.map((item) => (
          <div key={item.title} className="insight">
            <span className="insight-num">
              <i className={item.icon} />
            </span>


            <div>
              <strong>{item.title}</strong>
              <p>{item.text}</p>
            </div>
          </div>
        ))}
      </div>
    </div>
  )
}